"""Side-by-side comparison of the XGBoost and LSTM models.

python -m ml.compare_models          # prints the table and writes docs/model-comparison.md

Both models are scored on the same untouched test period (Oct 2025 - Oct 2026),
the same rows (location × issue time × lead hour) and with the same metric code,
so the numbers are directly comparable. Reads models/xgboost/metrics.json and
models/lstm/metrics.json.
"""
from __future__ import annotations

import json

from ml import config

DOC = config.ROOT / "docs" / "model-comparison.md"


def _load(name):
    p = config.MODEL_DIRS[name] / "metrics.json"
    return json.loads(p.read_text()) if p.exists() else None


def _cell(v, n=3):
    return "–" if v is None else f"{v:.{n}f}"


def compare() -> str:
    M = {n: _load(n) for n in config.MODEL_DIRS}
    have = [n for n, m in M.items() if m]
    if len(have) < 2:
        missing = [n for n in M if not M[n]]
        raise SystemExit(f"metrics missing for: {', '.join(missing)} (train it first)")
    meta = {n: json.loads((config.MODEL_DIRS[n] / "model_metadata.json").read_text()) for n in have}
    L = ["# XGBoost vs LSTM", "",
         "Generated by `python -m ml.compare_models` from `models/xgboost/metrics.json` and `models/lstm/metrics.json`.",
         "Same test period (issue times from Oct 2025), same locations, same metric code and the same rows, except that "
         "the LSTM skips the last day of issue times, whose 24 h window runs past the end of the dataset (see *Rows scored*). "
         "Lower MAE / RMSE is better; R² closer to 1 is better; 90 % interval coverage should be close to 0.90.", ""]
    for t, unit, nd in [("ozone", "µg/m³", 3), ("uv", "UV index", 3)]:
        L += [f"## {'Surface ozone (µg/m³)' if t == 'ozone' else 'UV index'}", "",
              "| Metric | XGBoost | LSTM | Better |", "|---|---|---|---|"]
        rows = [
            ("Rows scored (test)", lambda m: float(m["test"][t]["model"]["n"]), "info"),
            ("Test MAE (seen locations)", lambda m: m["test"][t]["model"]["mae"], "low"),
            ("Test RMSE", lambda m: m["test"][t]["model"]["rmse"], "low"),
            ("Test R²", lambda m: m["test"][t]["model"]["r2"], "high"),
            ("Holdout MAE (8 unseen locations)", lambda m: m["spatial_holdout_test"][t]["model"]["mae"], "low"),
            ("Holdout R²", lambda m: m["spatial_holdout_test"][t]["model"]["r2"], "high"),
            ("90 % range coverage (holdout)", lambda m: m["spatial_holdout_test"][t]["interval_90"]["coverage"], "cov"),
            ("90 % range coverage (test)", lambda m: m["test"][t]["interval_90"]["coverage"], "cov"),
            ("90 % range mean width (test)", lambda m: m["test"][t]["interval_90"]["mean_width"], "low"),
            ("MAE at lead 1 h", lambda m: m["test"][t]["by_lead"]["1"]["model"]["mae"] if "1" in m["test"][t]["by_lead"]
             else m["test"][t]["by_lead"][1]["model"]["mae"], "low"),
            ("MAE at lead 24 h", lambda m: m["test"][t]["by_lead"]["24"]["model"]["mae"] if "24" in m["test"][t]["by_lead"]
             else m["test"][t]["by_lead"][24]["model"]["mae"], "low"),
        ]
        if t == "uv":
            rows.append(("UV risk-class accuracy (daytime)",
                         lambda m: m["test"]["uv"]["risk_classification"]["daytime_only"]["accuracy"], "high"))
        for label, f, rule in rows:
            x, y = f(M["xgboost"]), f(M["lstm"])
            if rule == "info":
                L.append(f"| {label} | {x:,.0f} | {y:,.0f} | |")
                continue
            if rule == "low":
                best = "XGBoost" if x < y else "LSTM"
            elif rule == "high":
                best = "XGBoost" if x > y else "LSTM"
            else:
                best = "XGBoost" if abs(x - 0.9) < abs(y - 0.9) else "LSTM"
            if abs(x - y) <= 1e-3 * max(abs(x), abs(y), 1e-9):
                best = "tie"
            L.append(f"| {label} | {_cell(x, nd)} | {_cell(y, nd)} | {best} |")
        L.append("")
    L += ["## By region (test MAE, ozone / UV)", "", "| Region | XGBoost | LSTM |", "|---|---|---|"]
    for r in sorted(M["xgboost"]["test"]["ozone"]["by_region"]):
        g = lambda m, t: m["test"][t]["by_region"][r]["mae"]
        L.append(f"| {r} | {g(M['xgboost'], 'ozone'):.2f} / {g(M['xgboost'], 'uv'):.3f} | "
                 f"{g(M['lstm'], 'ozone'):.2f} / {g(M['lstm'], 'uv'):.3f} |")
    L += ["", "## Models", ""]
    for n in have:
        mm = meta[n]["models"]["ozone"]
        L.append(f"* **{n}**: {mm['algorithm']}, trained {meta[n].get('trained_at', '?')[:10]}; "
                 f"{meta[n].get('forecast_formulation', '')}.")
    L += ["", "## How to switch", "",
          "* Per request: `GET /api/v1/predictions/24h?lat=..&lon=..&model=lstm` (or `model=xgboost`).",
          "* Server default: set `OZONEGUARD_MODEL=lstm` in `.env` (default is `xgboost`).",
          "* Both side by side: `GET /api/v1/predictions/models`.", ""]
    return "\n".join(L)


def main() -> None:
    text = compare()
    DOC.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nwritten to {DOC.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
